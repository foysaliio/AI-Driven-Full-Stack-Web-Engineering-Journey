"use strict";
// void is commonly used when a function does not return a value.
function showMessage(message) {
    console.log(message);
}
showMessage("Hello Foysal");
// Another example
const printUser = (name, age) => {
    console.log(`Name: ${name}`);
    console.log(`Age: ${age}`);
};
printUser("Foysal", 22);
