"use strict";
// ReturnType extracts the return type of a function.
function getUser() {
    return {
        name: "Foysal",
        age: 22,
        email: "foysal@example.com",
    };
}
const user = {
    name: "Rahim",
    age: 25,
    email: "rahim@example.com",
};
console.log(user);
// Another example
function getPrice() {
    return 75000;
}
const price = 50000;
console.log(price);
