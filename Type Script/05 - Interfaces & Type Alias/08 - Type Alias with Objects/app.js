"use strict";
// A type alias can also define an object structure.
let product = {
    name: "Laptop",
    price: 75000,
    category: "Electronics",
};
console.log(product);
// Another product using the same type
let anotherProduct = {
    name: "Mouse",
    price: 1500,
    category: "Accessories",
};
console.log(anotherProduct);
