// Input: a string (lowercase letters only)
// Output: count of vowels
// Returns: a number

function countVowels(str) {
  let vowels = "aeiou";
  let count = 0;
  for (let i = 0; i < str.length; i++) {
    if (vowels.includes(str[i])) {
      count++;
    }
  }
  return count;
}

console.log(countVowels("javascript")); // Expected: 3
